def test_columns():
    import copy
    from anonymizer.config import DEFAULTS
    from anonymizer.columns import find_spans, detect
    cfg = copy.deepcopy(DEFAULTS)

    brevo = "\ufeffEMAIL;NOME;COGNOME;PHONE;BIRTHDAY;NOTE\nanna@esempio.it;Anna;Verdi;+39 333 1111111;1990-01-02;chiamare lunedi\n;;;;;\nb@esempio.it;\"Bianchi, Luca\";;;;\n"
    check("A4 detect csv ;", detect(brevo) == ("csv", ";"), detect(brevo))
    r = find_spans(brevo, cfg, [])
    check("A4 brevo cells whole, empty skipped, quoted cell inner, NOTE free",
          _cats(r) == [("DATA_NASCITA", "1990-01-02"), ("EMAIL", "anna@esempio.it"), ("EMAIL", "b@esempio.it"),
                       ("PERSONA", "Anna"), ("PERSONA", "Bianchi, Luca"), ("PERSONA", "Verdi"), ("TEL", "+39 333 1111111")],
          _cats(r))
    check("A4 offsets exact", all(brevo[s.start:s.end] == s.value for s in r), [(s, brevo[s.start:s.end]) for s in r])

    tsv = "Customer e-mail*\tLastname*\tFirstname*\tCompany\tVAT number\n" + "x@y.it\tRossi\tMario\tACME Srl\t04739200790\n" + "z@y.it\tNeri\tPia\t\t\n"
    r = find_spans(tsv, cfg, [])
    check("A4 prestashop tsv with * headers",
          _cats(r) == [("EMAIL", "x@y.it"), ("EMAIL", "z@y.it"), ("ORG", "ACME Srl"), ("PERSONA", "Mario"),
                       ("PERSONA", "Neri"), ("PERSONA", "Pia"), ("PERSONA", "Rossi"), ("PIVA", "04739200790")], _cats(r))

    pix = "cliente,vat,email,pec,domini\nOrtensia Web,04739200790,a@ortensiaweb.example,,ortensiaweb.example | ortensiaweb.test\n"
    r = find_spans(pix, cfg, [])
    check("A4 pixelbox multi-value domini split",
          _cats(r) == [("DOMINIO", "ortensiaweb.example"), ("DOMINIO", "ortensiaweb.test"), ("EMAIL", "a@ortensiaweb.example"),
                       ("ORG", "Ortensia Web"), ("PIVA", "04739200790")], _cats(r))

    raw = "id_customer;firstname;lastname;email;passwd;secure_key;birthday;note\n7;Ugo;Blu;u@b.it;$2y$10$abc;deadbeef;1980-05-05;\n"
    r = find_spans(raw, cfg, [])
    check("A4 prestashop raw: passwd/secure_key -> SECRET, id ignored",
          [c for c, v in _cats(r)] == ["DATA_NASCITA", "EMAIL", "PERSONA", "PERSONA", "SECRET", "SECRET"], _cats(r))

    js = json.dumps([{"email": "j@k.it", "first_name": "Jo", "age": 3, "note": "x"}, {"email": "l@m.it", "first_name": "Al"}], indent=1, ensure_ascii=False)
    check("A4 detect json table", detect(js) == ("json",), detect(js))
    r = find_spans(js, cfg, [])
    check("A4 json table values with exact offsets",
          _cats(r) == [("EMAIL", "j@k.it"), ("EMAIL", "l@m.it"), ("PERSONA", "Al"), ("PERSONA", "Jo")]
          and all(js[s.start:s.end] == s.value for s in r), _cats(r))

    prose = "Gentile cliente, la sua pratica; è pronta, ritiri; entro, venerdì.\nAltro; testo, qui\n"
    check("A4 prose is not a table", detect(prose) is None and find_spans(prose, cfg, []) == [], detect(prose))

    c = copy.deepcopy(cfg); c["columns"]["extra"] = {"e": "EMAIL", "referente": "PERSONA"}
    ex = "e,referente,r\nq@w.it,Gia Neri,4\n"
    r = find_spans(ex, c, [])
    check("A4 columns.extra headers", _cats(r) == [("EMAIL", "q@w.it"), ("PERSONA", "Gia Neri")], _cats(r))

    c = copy.deepcopy(cfg); c["whitelist"] = ["ortensiaweb.example"]
    r = find_spans(pix, c, [])
    check("A4 whitelisted value skipped in cells", ("DOMINIO", "ortensiaweb.example") not in _cats(r), _cats(r))

    multi = "email,note\na@b.it,\"riga uno\nriga due\"\nc@d.it,x\n"
    r = find_spans(multi, cfg, [])
    check("A4 multiline quoted cell: doc skipped (no spans)", r == [], _cats(r))


