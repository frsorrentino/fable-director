#!/usr/bin/env python3
"""Deterministic verification of the anonymizer package (phase A).

Imports the REAL package from fable-director/anonymizer and runs the REAL CLI
against a throwaway HOME. No client data: every fixture is synthetic
(fable-director/anonymizer/corpus-public, generated by gen.py).

  A1  check digits: CF, P.IVA, IBAN, Luhn
  A2  rules: positives and negatives per category
  A3  span merge: longest wins, then engine priority; email never yields DOMINIO
  A4  columns: CSV ; TSV, JSON table, prose -> none, columns.extra
  A5  dictionary: exact, token with capital, ORG stems, whitelist
  A6  pmap: same normalized value -> same placeholder; chmod 600; tolerant restore
  A7  round-trip restore(redact(x)) == x on the public corpus
  A8  test --strict passes thresholds; report leaks no corpus value
  A9  CLI: STATUS on every command, scan writes no map, redact/restore --out, status --purge
  A10 performance <= 5 ms/KB on 200 KB
  A11 no catastrophic backtracking: seven pathological inputs, each under 1 s

Usage: python3 tests/anonymizer-verify.py   (exit 0 = all green)
"""
import json
import os
import stat
import subprocess
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLUGIN = HERE.parent / "fable-director"
SCRIPT = PLUGIN / "scripts" / "anonymizer.py"
FIXTURES = PLUGIN / "anonymizer" / "corpus-public"
sys.path.insert(0, str(PLUGIN))

passed, failed = [], []


def check(name, ok, evidence=""):
    (passed if ok else failed).append(name)
    print(f"{'PASS' if ok else 'FAIL'}  {name}" + ("" if ok else f"\n      {evidence}"))


def field(out, key):
    for line in out.splitlines():
        if line.startswith(key + ":"):
            return line.split(":", 1)[1].strip()
    return None


def run(home, args, stdin=None, cwd=None):
    env = dict(os.environ, HOME=str(home))
    return subprocess.run([sys.executable, str(SCRIPT)] + args, input=stdin,
                          capture_output=True, text=True, env=env,
                          cwd=str(cwd or home), timeout=120)


# ---------------------------------------------------------------- A1 / A2
def _cats(spans):
    return sorted((s.cat, s.value) for s in spans)


def test_rules():
    from anonymizer.rules.base import cf_ok, piva_ok, iban_ok, luhn_ok
    from anonymizer.rules import find_spans
    from anonymizer.config import DEFAULTS
    import copy
    cfg = copy.deepcopy(DEFAULTS)

    check("A1 CF check digit", cf_ok("RSSMRA80A01H501U") and not cf_ok("RSSMRA80A01H501A"))
    check("A1 P.IVA check digit", piva_ok("04739200790") and not piva_ok("04739200791"))
    check("A1 IBAN mod 97", iban_ok("IT60X0542811101000000123456") and not iban_ok("IT60X0542811101000000123457")
          and iban_ok("DE89370400440532013000"))
    check("A1 Luhn", luhn_ok("4539578763621486") and not luhn_ok("4539578763621487"))

    def spans(text, **over):
        c = copy.deepcopy(cfg)
        c["rules"].update(over)
        return find_spans(text, c, [])

    r = spans("scrivi a Mario.Rossi@Example.it oggi")
    check("A2 EMAIL found, no DOMINIO from its host",
          _cats(r) == [("EMAIL", "Mario.Rossi@Example.it")], _cats(r))

    r = spans("il fatturato 2024 è di 1331234567 euro; ordine n. 0961123456; cell 3331234567")
    check("A2 TEL: bare fixed number ignored by default, mobile format always taken",
          [v for c, v in _cats(r) if c == "TEL"] == ["3331234567"], _cats(r))
    r = spans("tel. 0962 123456, cell 333 1234567, +39 06 12345678, whatsapp: 3471234567, 0039 320 1234567")
    check("A2 TEL with context, +39, 0039", [v for c, v in _cats(r) if c == "TEL"] ==
          sorted(["0962 123456", "333 1234567", "+39 06 12345678", "3471234567", "0039 320 1234567"]), _cats(r))
    r = spans("fisso 0962 123456", tel_requires_context=False)
    check("A2 TEL without context when tel_requires_context=false", ("TEL", "0962 123456") in _cats(r), _cats(r))
    r = spans("call +44 20 7946 0958 or +1 415 555 2671")
    check("A2 TEL foreign with + prefix", len([1 for c, v in _cats(r) if c == "TEL"]) == 2, _cats(r))

    r = spans("sede in Via Roma 12, 88900 Crotone (KR) e via SGR 2 non conta")
    check("A2 INDIRIZZO with CAP included, ANSI-like 'via SGR 2' excluded",
          _cats(r) == [("INDIRIZZO", "Via Roma 12, 88900 Crotone (KR)")], _cats(r))
    r = spans("residente in piazza Giuseppe Garibaldi n. 3 a Catanzaro")
    check("A2 INDIRIZZO with n. and no CAP", _cats(r) == [("INDIRIZZO", "piazza Giuseppe Garibaldi n. 3")], _cats(r))

    r = spans("server 127.0.0.1, 0.0.0.0, 192.168.1.10, 10.0.0.5, 172.16.3.4, 169.254.1.1 e 8.8.8.8")
    check("A2 IP: loopback/private/link-local excluded, public kept", _cats(r) == [("IP", "8.8.8.8")], _cats(r))

    r = spans("vedi https://github.com/frsorrentino/x e https://img.shields.io/badge e https://cliente-finale.it/p?q=1")
    check("A2 URL domain-only, whitelist hosts skipped", _cats(r) == [("DOMINIO", "cliente-finale.it")], _cats(r))
    r = spans("vedi https://cliente-finale.it/p?q=1", url="full")
    check("A2 URL full mode", _cats(r) == [("URL", "https://cliente-finale.it/p?q=1")], _cats(r))
    r = spans("vedi https://cliente-finale.it/p", url="off")
    check("A2 URL off", _cats(r) == [], _cats(r))

    r = spans("CF RSSMRA80A01H501U e RSSMRA80A01H501A")
    check("A2 CF valid only", _cats(r) == [("CF", "RSSMRA80A01H501U")], _cats(r))
    r = spans("P.IVA 04739200790, IT04739200790, prot. n. 04739200790, pezzi 04739200791")
    check("A2 PIVA with context/IT prefix, not after prot., check digit enforced",
          [v for c, v in _cats(r) if c == "PIVA"] == ["04739200790", "04739200790"], _cats(r))
    r = spans("IBAN IT60 X054 2811 1010 0000 0123 456 e IT60X0542811101000000123457 e DE89 3704 0044 0532 0130 00")
    check("A2 IBAN it spaced + generic, invalid dropped",
          [v for c, v in _cats(r) if c == "IBAN"] == ["DE89 3704 0044 0532 0130 00", "IT60 X054 2811 1010 0000 0123 456"], _cats(r))
    r = spans("carta 4539 5787 6362 1486 e 4539 5787 6362 1487")
    check("A2 CARTA Luhn", [v for c, v in _cats(r) if c == "CARTA"] == ["4539 5787 6362 1486"], _cats(r))
    r = spans("targa FA 123 BC, EX123YZ, IO 123 QU")
    check("A2 TARGA format, IOQU excluded", [v for c, v in _cats(r) if c == "TARGA"] == ["EX123YZ", "FA 123 BC"], _cats(r))
    r = spans("nato a Crotone il 12/03/1985, data di nascita: 1985-03-12, riunione del 12/03/2026")
    check("A2 DATA_NASCITA only with context", [v for c, v in _cats(r) if c == "DATA_NASCITA"] == ["12/03/1985", "1985-03-12"], _cats(r))
    r = spans("prot. n. 12345/2026 e R.G. 4567/2025 e fascicolo n. 88")
    check("A2 PROTOCOLLO", [v for c, v in _cats(r) if c == "PROTOCOLLO"] == ["12345/2026", "4567/2025", "88"], _cats(r))

    from anonymizer.spans import Span
    taken = [Span(9, 31, "EMAIL", "Mario.Rossi@Example.it", "columns")]
    r = find_spans("scrivi a Mario.Rossi@Example.it oggi", cfg, taken)
    check("A2 rules skip regions already taken", r == [], r)
    r = spans("contatta Pixelfarm su https://pixelfarm.it e info@pixelfarm.it")
    check("A2 non-whitelisted host: DOMINIO and EMAIL both redacted",
          _cats(r) == [("DOMINIO", "pixelfarm.it"), ("EMAIL", "info@pixelfarm.it")], _cats(r))
    c = copy.deepcopy(cfg); c["whitelist"] = ["pixelfarm.it"]
    r = find_spans("contatta https://pixelfarm.it e info@pixelfarm.it", c, [])
    check("A2 whitelisted host: domain skipped, e-mail still redacted",
          _cats(r) == [("EMAIL", "info@pixelfarm.it")], _cats(r))


