def test_corpus():
    import copy
    from anonymizer import corpus
    from anonymizer.config import DEFAULTS, _merge
    docs = corpus.load(FIXTURES)
    check("A7 public corpus loads with annotations", len(docs) >= 8 and all(d.spans for d in docs), [d.id for d in docs])
    cfg = _merge(copy.deepcopy(DEFAULTS), corpus.config_override(FIXTURES))
    bad = corpus.validate(docs)
    check("A7 annotations match document text", bad == [], bad)
    m = corpus.evaluate(docs, cfg)
    formatted = m["formatted"]
    check("A7 formatted categories recall >= 0.99 precision >= 0.90",
          formatted["recall"] >= 0.99 and formatted["precision"] >= 0.90,
          {k: v for k, v in m["per_category"].items() if v["fp"] or v["fn"]})
    check("A7 PERSONA reported but informative", "PERSONA" in m["per_category"] and "PERSONA" not in corpus.FORMATTED)
    failed_rt = corpus.roundtrip(docs, cfg)
    check("A7 round-trip restore(redact(x)) == x on every doc", failed_rt == [], failed_rt)
    check("A7 metrics carry no values", "@" not in json.dumps(m) and not any(d.text[:20] in json.dumps(m) for d in docs))


