def test_spans_and_pmap(home):
    from anonymizer.spans import Span, merge_spans, apply_spans
    from anonymizer.pmap import PlaceholderMap, normalize, map_path

    long = Span(0, 30, "INDIRIZZO", "Via Roma 12, 88900 Crotone (KR)", "rules")
    short = Span(13, 18, "CAP_COMUNE", "88900", "rules")
    merged = merge_spans([short, long])
    check("A3 longest span wins on overlap", merged == [long], repr(merged))

