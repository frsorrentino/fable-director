def test_cli(home):
    from anonymizer.pmap import map_path
    r = run(home, ["test", "--strict", "--json"])
    check("A8 test --strict on public corpus passes", r.returncode == 0 and field(r.stdout, "STATUS") == "ok", r.stdout[-800:] + r.stderr[-800:])
    values = []
    for f in (FIXTURES / "docs").glob("*.spans.json"):
        values += [s["text"] for s in json.loads(f.read_text())["spans"]]
    leaked = [v for v in values if v in r.stdout]
    check("A8 test report leaks no corpus value", leaked == [], leaked[:5])
    check("A8 test report names public corpus only (no private dir in throwaway HOME)", "public" in r.stdout and "private" not in field(r.stdout, "DETAIL"), field(r.stdout, "DETAIL"))

    src = FIXTURES / "docs" / "email-thread.txt"
    maps_dir = map_path("x", home).parent
    before = sorted(p.name for p in maps_dir.glob("*")) if maps_dir.is_dir() else []
    r = run(home, ["scan", str(src), str(FIXTURES / "docs" / "export-brevo.txt")])
    check("A9 scan prints STATUS ok and counts", r.returncode == 0 and field(r.stdout, "STATUS") == "ok" and "EMAIL" in r.stdout, r.stdout)
    after = sorted(p.name for p in maps_dir.glob("*")) if maps_dir.is_dir() else []
    check("A9 scan writes no map", before == after, (before, after))
    r = run(home, ["scan", str(src), "--json"])
    check("A9 scan --json is parseable and value-free", '"counts"' in r.stdout and "@" not in r.stdout.split("STATUS:")[0], r.stdout[:300])

    out = home / "red.txt"
    r = run(home, ["redact", str(src), "--map", "sess1", "--out", str(out)])
    red = out.read_text()
    check("A9 redact --out writes placeholders and the map", r.returncode == 0 and field(r.stdout, "STATUS") == "ok"
          and "[EMAIL_1]" in red and "@" not in red and map_path("sess1", home).is_file(), r.stdout + r.stderr)
    back = home / "back.txt"
    r = run(home, ["restore", str(out), "--map", "sess1", "--out", str(back)])
    check("A9 restore --out round-trips", r.returncode == 0 and back.read_text() == src.read_text(), r.stdout + r.stderr)
    r = run(home, ["redact", "--stdin", "--map", "sess1"], stdin="scrivi a " + json.loads((FIXTURES / "docs" / "email-thread.spans.json").read_text())["spans"][1]["text"] + " subito\n")
    check("A9 redact --stdin reuses the map and prints text on stdout, STATUS on stderr",
          r.stdout == "scrivi a [EMAIL_1] subito\n" and field(r.stderr, "STATUS") == "ok", r.stdout + r.stderr)
    r = run(home, ["restore", "--stdin", "--map", "nope"], stdin="x")
    check("A9 restore with missing map is an error", r.returncode == 1 and field(r.stderr, "STATUS") == "error", r.stdout + r.stderr)
    r = run(home, ["redact", str(home / "missing.txt")])
    check("A9 redact missing file is an error (STATUS on stderr without --out)", r.returncode == 1 and field(r.stderr, "STATUS") == "error", r.stdout + r.stderr)
    binp = home / "bin.dat"; binp.write_bytes(b"\x00\x01\xff\xfe" * 100)
    r = run(home, ["scan", str(binp)])
    check("A9 binary file refused", r.returncode == 1 and "not text" in r.stdout, r.stdout)

    old = map_path("old", home)
    d = json.loads(map_path("sess1", home).read_text()); d["created"] = "2020-01-01T00:00:00+00:00"
    old.write_text(json.dumps(d))
    r = run(home, ["status"])
    check("A9 status lists maps and flags expired", field(r.stdout, "STATUS") == "ok" and "sess1" in r.stdout and "old" in r.stdout and "expired" in r.stdout, r.stdout)
    r = run(home, ["status", "--purge"])
    check("A9 status --purge removes expired map only", not old.exists() and map_path("sess1", home).exists() and field(r.stdout, "STATUS") == "ok", r.stdout)
    r = run(home, ["frobnicate"])
    check("A9 unknown command is an error with usage", r.returncode != 0 and ("usage" in (r.stdout + r.stderr).lower()), r.stdout + r.stderr)

    big = home / "big.txt"
    big.write_text(src.read_text() * (200_000 // len(src.read_text()) + 1))
    t0 = time.perf_counter(); r = run(home, ["scan", str(big), "--json"]); wall = time.perf_counter() - t0
    rep = json.loads(r.stdout.split("STATUS:")[0])
    ms_kb = rep[0]["ms"] / (rep[0]["chars"] / 1024)
    check("A10 scan <= 5 ms/KB on 200 KB", ms_kb <= 5.0, f"{ms_kb:.2f} ms/KB, wall {wall:.2f}s")

    # A11 — ReDoS: every rule must stay linear-ish on adversarial input
    # (nested quantifiers in the address, CAP, phone and e-mail rules).
    import copy
    from anonymizer.rules import find_spans
    from anonymizer.config import DEFAULTS
    cfg = copy.deepcopy(DEFAULTS)
    cases = {"via+parole": "via " + "Aaaa " * 3000 + "!", "prot cifre": "prot. n. " + "1" * 5000 + "x",
             "tel separatori": "tel. 3" + " 3" * 4000 + "x", "cap comune": "88900 " + "Aaaa " * 3000 + "?",
             "iban-like": "IT" + "12" * 3000 + "!", "nato il": "nato a " + "a" * 3000 + " il x",
             "email-like": "a" * 5000 + "@" + "b" * 5000 + "!"}
    slow = {}
    for name, text in cases.items():
        t0 = time.perf_counter()
        find_spans(text, cfg, [])
        ms = (time.perf_counter() - t0) * 1000
        if ms > 1000:
            slow[name] = round(ms)
    check("A11 no catastrophic backtracking (each pathological input < 1 s)", not slow, slow)


