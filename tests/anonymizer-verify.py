def test_dictionary_and_engine(home):
    import copy
    from anonymizer.config import DEFAULTS, load
    from anonymizer.dictionary import find_spans, stems
    from anonymizer import engine
    from anonymizer.pmap import PlaceholderMap
    cfg = copy.deepcopy(DEFAULTS)
    cfg["dictionary"].update({"PERSONA": ["Mario Rossi", "Anna Verdi"], "ORG": ["Ortensia Web S.r.l.s.", "Officine Zampolini SRL"],
                              "DOMINIO": ["ortensiaweb.example"]})
    cfg["whitelist"] += ["Rossini"]

    check("A5 stems", stems("Ortensia Web S.r.l.s.") == ["ortensia web s.r.l.s.", "ortensia web"]
          and stems("Officine Zampolini SRL") == ["officine zampolini srl", "officine zampolini"], stems("Ortensia Web S.r.l.s."))

    t = "Ho sentito MARIO ROSSI e la sig.ra Verdi; Rossi ha firmato. I rossi sono colori. Rossini no."
    r = find_spans(t, cfg, [])
    check("A5 exact casefold + token with capital, lowercase token ignored, whitelist",
          _cats(r) == [("PERSONA", "MARIO ROSSI"), ("PERSONA", "Rossi"), ("PERSONA", "Verdi")], _cats(r))
    t = "Fattura a Ortensia Web srls e a ortensia web per il sito ortensiaweb.example; officine zampolini paga."
    r = find_spans(t, cfg, [])
    check("A5 ORG stems and DOMINIO", _cats(r) == [("DOMINIO", "ortensiaweb.example"), ("ORG", "Ortensia Web"), ("ORG", "officine zampolini"),
                                                   ("ORG", "ortensia web")], _cats(r))

    text = "Cliente Mario Rossi, mail mario@ortensiaweb.example, tel 333 1234567, CF RSSMRA80A01H501U, sito https://ortensiaweb.example/x"
    pm = PlaceholderMap()
    out, rep = engine.redact(text, pm, cfg)
    check("A6/engine redact replaces every category once",
          out == "Cliente [PERSONA_1], mail [EMAIL_1], tel [TEL_1], CF [CF_1], sito https://[DOMINIO_1]/x", out)
    check("engine report has counts only",
          rep["counts"] == {"PERSONA": 1, "EMAIL": 1, "TEL": 1, "CF": 1, "DOMINIO": 1} and set(rep["by_engine"]) <= {"rules", "dictionary", "columns"}
          and "Rossi" not in json.dumps(rep), rep)
    back, info = engine.restore(out, pm)
    check("engine restore round-trip", back == text and info["restored"] == 5, back)
    rep2 = engine.scan(text, cfg)
    check("engine scan same counts, map untouched", rep2["counts"] == rep["counts"] and pm.counts() == {"PERSONA": 1, "EMAIL": 1, "TEL": 1, "CF": 1, "DOMINIO": 1}, rep2)
    out2, _ = engine.redact("Rossi e mario@ortensiaweb.example di nuovo", pm, cfg)
    check("engine placeholders stable across calls (surname alone is its own value)", out2 == "[PERSONA_2] e [EMAIL_1] di nuovo", out2)

    proj = home / "proj" / "sub"
    proj.mkdir(parents=True)
    (home / "proj" / ".git").mkdir()
    (home / "proj" / ".fd-anonymizer.json").write_text(json.dumps({"dictionary": {"PERSONA": ["Pia Neri"]}, "whitelist": ["Crotone"],
                                                                     "columns": {"extra": {"ref": "PERSONA"}}, "guard": "deny"}))
    (home / ".claude" / "fable-director").mkdir(parents=True, exist_ok=True)
    (home / ".claude" / "fable-director" / "anonymizer.json").write_text(json.dumps({"rules": {"url": "full"}, "whitelist": ["x.it"]}))
    c = load(cwd=proj, home=home)
    check("config merge default <- global <- project (found upwards to .git)",
          c["rules"]["url"] == "full" and c["guard"] == "deny" and "Crotone" in c["whitelist"] and "x.it" in c["whitelist"]
          and "github.com" in c["whitelist"] and c["dictionary"]["PERSONA"] == ["Pia Neri"] and c["columns"]["extra"] == {"ref": "PERSONA"}
          and c["rules"]["tel_requires_context"] is True and len(c["_sources"]) == 2, c)


